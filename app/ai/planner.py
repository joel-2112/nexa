"""Planner that translates intent and requirements into executable Action Plans."""

from __future__ import annotations

from sqlalchemy.ext.asyncio import AsyncSession

from app.ai.agent import NexaAgent
from app.ai.schemas import ExtractedIntent, IntentType
from app.core.logging import get_logger
from app.db.models import (
    ActionPlan,
    ActionPlanStatus,
    ActionStep,
    ActionStepStatus,
    Conversation,
    User,
)

logger = get_logger(__name__)


class NexaPlanner:
    def __init__(self, db: AsyncSession, agent: NexaAgent | None = None) -> None:
        self.db = db
        self.agent = agent or NexaAgent()

    async def create_action_plan(
        self,
        intent: ExtractedIntent,
        user: User,
        conversation: Conversation | None = None,
    ) -> ActionPlan:
        """Construct an ActionPlan with discrete, ordered steps."""
        if intent.intent == IntentType.SCHEDULE_MEETING:
            return await self._plan_meeting_workflow(intent, user, conversation)
        elif intent.intent == IntentType.CREATE_TASK:
            return await self._plan_task_workflow(intent, user, conversation)
        else:
            return await self._plan_generic_workflow(intent, user, conversation)

    async def _plan_meeting_workflow(
        self,
        intent: ExtractedIntent,
        user: User,
        conversation: Conversation | None = None,
    ) -> ActionPlan:
        entities = intent.entities
        topic = entities.get("topic", "Client Meeting")
        client_name = entities.get("client_name", "Client")
        client_email = entities.get("client_email")
        start_time = entities.get("start_time")
        end_time = entities.get("end_time")

        title = f"Meeting with {client_name} - {topic}"
        description = (
            f"Automated meeting plan generated by NEXA:\n"
            f"- Topic: {topic}\n"
            f"- Attendee: {client_name} ({client_email})\n"
            f"- Proposed Time: {start_time} to {end_time}"
        )

        steps = []
        step_order = 1

        # Step 1: Check availability
        step1 = ActionStep(
            step_order=step_order,
            tool_name="check_calendar_availability",
            description=f"Check calendar availability for {start_time}",
            arguments={"start_time": start_time, "end_time": end_time},
            requires_approval=False,
            status=ActionStepStatus.pending,
        )
        steps.append(step1)
        step_order += 1

        # Step 2: Create Google Calendar Event with Meet Link
        step2 = ActionStep(
            step_order=step_order,
            tool_name="create_calendar_event",
            description=f"Create calendar event '{title}' with Google Meet link",
            arguments={
                "title": title,
                "start_time": start_time,
                "end_time": end_time,
                "description": f"Topic: {topic}",
                "attendee_emails": [client_email] if client_email else [],
                "add_google_meet": True,
            },
            requires_approval=True,
            status=ActionStepStatus.pending,
        )
        steps.append(step2)
        step_order += 1

        # Step 3: Send Client Invitation Email if email provided
        if client_email:
            step3 = ActionStep(
                step_order=step_order,
                tool_name="send_email_invitation",
                description=f"Send meeting confirmation email to {client_email}",
                arguments={
                    "to_email": client_email,
                    "subject": f"Invitation: {title}",
                    "body": (
                        f"Hello {client_name},\n\n"
                        f"You are invited to: {title}\n"
                        f"Time: {start_time}\n\n"
                        f"A Google Meet link will be provided in the calendar invite.\n\n"
                        f"Best regards,\n{user.full_name}"
                    ),
                },
                requires_approval=True,
                status=ActionStepStatus.pending,
            )
            steps.append(step3)
            step_order += 1

        # Step 4: Create preparation task
        step4 = ActionStep(
            step_order=step_order,
            tool_name="create_task",
            description=f"Create preparation task: Review materials for {topic}",
            arguments={
                "title": f"Prep for {title}",
                "description": f"Review project specs and agenda for {topic} with {client_name}",
                "due_date": start_time,
                "priority": "high",
            },
            requires_approval=True,
            status=ActionStepStatus.pending,
        )
        steps.append(step4)
        step_order += 1

        # Step 5: Schedule 10-minute prior reminder
        if start_time:
            from datetime import timedelta

            from dateutil import parser

            try:
                dt_start = parser.parse(start_time)
                dt_remind = dt_start - timedelta(minutes=10)
                remind_str = dt_remind.isoformat()
            except Exception:
                remind_str = start_time

            step5 = ActionStep(
                step_order=step_order,
                tool_name="schedule_reminder",
                description="Schedule reminder 10 minutes before the meeting",
                arguments={
                    "event_title": title,
                    "remind_at": remind_str,
                    "channel": "telegram",
                },
                requires_approval=True,
                status=ActionStepStatus.pending,
            )
            steps.append(step5)

        plan = ActionPlan(
            user_id=user.id,
            conversation_id=conversation.id if conversation else None,
            title=title,
            description=description,
            intent=intent.intent.value,
            status=ActionPlanStatus.pending_approval,
            plan_data=entities,
            steps=steps,
        )
        self.db.add(plan)
        await self.db.flush()
        return plan

    async def _plan_task_workflow(
        self, intent: ExtractedIntent, user: User, conversation: Conversation | None
    ) -> ActionPlan:
        entities = intent.entities
        title = entities.get("title", "New Task")
        due_date = entities.get("due_date")
        priority = entities.get("priority", "medium")

        plan = ActionPlan(
            user_id=user.id,
            conversation_id=conversation.id if conversation else None,
            title=f"Create Task: {title}",
            description=f"Task creation for '{title}' (Priority: {priority}, Due: {due_date})",
            intent=intent.intent.value,
            status=ActionPlanStatus.pending_approval,
            plan_data=entities,
        )
        self.db.add(plan)
        await self.db.flush()

        step = ActionStep(
            plan_id=plan.id,
            step_order=1,
            tool_name="create_task",
            description=f"Add task '{title}' to user task list",
            arguments={"title": title, "due_date": due_date, "priority": priority},
            requires_approval=True,
            status=ActionStepStatus.pending,
        )
        self.db.add(step)
        await self.db.flush()
        return plan

    async def _plan_generic_workflow(
        self, intent: ExtractedIntent, user: User, conversation: Conversation | None
    ) -> ActionPlan:
        plan = ActionPlan(
            user_id=user.id,
            conversation_id=conversation.id if conversation else None,
            title=f"Execute {intent.intent.value.replace('_', ' ').title()}",
            description="Automated execution plan",
            intent=intent.intent.value,
            status=ActionPlanStatus.pending_approval,
            plan_data=intent.entities,
        )
        self.db.add(plan)
        await self.db.flush()
        return plan
